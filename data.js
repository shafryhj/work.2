function getAvgRevenueByDayOfWeek() {
  const groups = {};
  DAY_ORDER_UNIQUE.forEach(d => { groups[d] = []; });
  DAILY_DATA.forEach((d, i) => {
    groups[d.dayOfWeek].push(dailyRevenues[i]);
  });
  const result = {};
  DAY_ORDER_UNIQUE.forEach(day => {
    const arr = groups[day];
    result[day] = arr.length > 0 ? Math.round(arr.reduce((a, b) => a + b, 0) / arr.length) : 0;
  });
  return result;
}

